package com.Steven.OrderSystem.enums;

/**
 * Enumeración que define los tipos de productos disponibles en el sistema.
 * Representa la categoría general del producto.
 */
public enum ProductType {
    /**
     * Productos relacionados con higiene personal y limpieza
     */
    HYGIENE,
    
    /**
     * Productos empaquetados (procesados)
     */
    PACKAGED,
    
    /**
     * Productos fríos que requieren refrigeración
     */
    COLD,
    
    /**
     * Carnes y derivados
     */
    MEATS,
    
    /**
     * Productos de variedades generales
     */
    VARIETIES
}
